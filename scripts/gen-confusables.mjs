// Generates src/lib/confusables-data.ts from data/unicode/confusables.txt (UTS #39, Unicode License v3).
// Run after updating the data file: node scripts/gen-confusables.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const src = readFileSync('data/unicode/confusables.txt', 'utf8')
const version = /# Version: (\S+)/.exec(src)?.[1] ?? 'unknown'
const pairs = []
for (const line of src.split('\n')) {
  const m = /^([0-9A-F ]+?)\s*;\s*([0-9A-F ]+?)\s*;\s*MA/.exec(line)
  if (!m) continue
  const from = m[1].trim().split(/\s+/).map((h) => Number.parseInt(h, 16))
  if (from.length !== 1) continue
  const to = m[2].trim().split(/\s+/).map((h) => Number.parseInt(h, 16))
  pairs.push([from[0], to])
}
const esc = (cps) => cps.map((c) => (c < 0x10000 ? `\\u${c.toString(16).padStart(4, '0')}` : `\\u{${c.toString(16)}}`)).join('')
const body = pairs.map(([f, t]) => `${esc([f])}\\t${esc(t)}`).join('\\n')
writeFileSync(
  'src/lib/confusables-data.ts',
  `// Generated by scripts/gen-confusables.mjs from data/unicode/confusables.txt — do not edit.
// Unicode Security Mechanisms (UTS #39) confusables, version ${version}. © Unicode, Inc., Unicode License v3 (data/unicode/LICENSE.txt).
export const CONFUSABLES_VERSION = '${version}'
const PACKED = '${body}'
export const CONFUSABLES: ReadonlyMap<string, string> = new Map(PACKED.split('\\n').map((l) => l.split('\\t') as [string, string]))
`,
)
console.log(`${pairs.length} mappings, version ${version}`)
